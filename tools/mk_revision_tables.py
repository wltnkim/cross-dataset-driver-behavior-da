import statistics as _st

def chance_of(target):
    return 1 / 6 if target in ("obc", "driveandact") else 0.2

lines = []
lines.append(r"% Table 3h: selection-rule finding (compact), adversarial vs source-only vs chance.")
lines.append(r"% Generated by tools/mk_revision_tables.py from analysis/swan_campaign_2026-09-07/reeval_cells.csv.")
