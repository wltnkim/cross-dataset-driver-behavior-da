def cell(group, method, source, target):
    for r in cells:
        if r["group"] == group and r["method"] == method and r["source"] == source and r["target"] == target:
            return r
    return None


def fmt(mean, spread, dp=3):
    return f"{float(mean):.{dp}f} $\\pm$ {float(spread):.{dp}f}" if spread not in (None, "") else f"{float(mean):.{dp}f}"


citation_rows = []  # (table, row_desc, field, value, source_csv, source_column)


def cite(table, row_desc, field, value, source_csv, source_column):
    citation_rows.append([table, row_desc, field, value, source_csv, source_column])


