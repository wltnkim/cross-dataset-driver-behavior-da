lines.append(r"\caption{Selection-rule finding: mean test BA under each label-free rule, adversarial "
             r"cells (DANN+CDAN, $n{=}27$) vs.\ source-only cells ($n{=}10$), against each cell's own "
             r"target chance. Every adversarial cell sits at or below chance under every label-free "
             r"rule; every source-only cell sits above chance by more than the noise floor "
             r"(0.077445) under all three rules.}")
lines.append(r"\label{tab:selection_rule_finding}")
lines.append(r"\footnotesize")
lines.append(r"\begin{tabular}{llrrr}")
lines.append(r"\toprule")
lines.append(r"Population & Rule & mean & mean $-$ chance & $n$ above chance \\")
lines.append(r"\midrule")
for poplabel, pred, n in (("Adversarial", lambda r: r["method"] in ("dann", "cdan"), 27),
                           ("Source-only", lambda r: r["method"] == "source_only", 10)):
    grp = [r for r in cells if pred(r)]
    for rule in ("source_val", "last_epoch", "min_target_entropy"):
        vals = [float(r[f"{rule}_mean"]) for r in grp]
        chances = [chance_of(r["target"]) for r in grp]
        mean = _st.mean(vals)
        mean_minus_chance = mean - _st.mean(chances)
        n_above = sum(1 for v, c in zip(vals, chances) if v > c)
        lines.append(f"{poplabel} & {RULE_LABEL[rule]} & {mean:.4f} & {mean_minus_chance:+.4f} & "
                     f"{n_above}/{len(grp)} \\\\")
        cite("8_selection_rule_finding", f"{poplabel}/{rule}", "mean, mean-chance, n_above",
             f"{mean:.6f}", "reeval_cells.csv",
             f"filter(group in ...,method matches {poplabel}): {rule}_mean per row, vs target chance")
    lines.append(r"\midrule" if poplabel == "Adversarial" else "")
lines[-1] = r"\bottomrule"
lines.append(r"\end{tabular}")
lines.append(r"\end{table}")
open(os.path.join(OUT, "8_selection_rule_finding.tex"), "w").write("\n".join(lines) + "\n")

